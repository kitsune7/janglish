"""
Generate same-speaker code-switched EN/JA audio + frame-level language labels.

Uses XTTS v2 (Coqui) with voice cloning. Code-switched sentences are generated
as two full-sentence renders with the same cloned speaker:

  * An English render uses language="en" and converts Japanese spans to romaji.
  * A Japanese render uses language="ja" and the original mixed-script text.
  * The final clip stitches English spans from the English render and Japanese
    spans from the Japanese render. Pure single-language rows only need one
    render.

Span boundaries (for frame-level language labels) are recovered with forced
alignment: torchaudio's MMS_FA aligner matches the audio against the known
romanized transcript and yields word-level timestamps. Alignment also tells us
where real speech starts/ends, which trims XTTS's trailing babble/noise —
the classic end-of-clip hallucination — from every generated render.

Earlier versions stitched per-span mini-clips with a crossfade. That fails
badly: XTTS degenerates on short text fragments (babble, multi-second silence
padding), and stitching produces choppy prosody and loudness jumps. This script
only stitches cuts from full-sentence renders.

CSV format (no header by default; pass --has-header if yours has one):
    path/to/output.wav | the sentence to encode, 日本語 included
    manual/... rows are recorded clips and are ignored for synthesis.

Outputs per row:
    {out-root}/{path}.wav     — mono 16-bit PCM at TARGET_SR
    {out-root}/{path}.json    — span boundaries + frame-level language labels

Sidecar JSON shape:
    {
      "audio_path": "...",
      "sentence": "...",
      "sample_rate": 16000,
      "duration_ms": 2345,
      "reference_speaker": "ref_0037.wav",
      "tts_language": "stitched",
      "alignment": "forced-dual",     # or "partial-fallback-dual"
      "spans": [
        {"lang": "en", "text": "Hello,", "start_ms": 0, "end_ms": 850,
         "start_sample": 0, "end_sample": 13600},
        ...
      ],
      "frame_rate_hz": 50,
      "num_frames": 117,
      "frame_labels": "eeee...jjjj..."   # 'e'=EN, 'j'=JA, 'a'=ambiguous boundary
    }

Requirements:
    uv add "coqui-tts[codec,ja]" soundfile python-dotenv numpy torch torchaudio
    uv add fugashi pykakasi unidic-lite

License caveat: XTTS v2 ships under the Coqui Public Model License (CPML) —
non-commercial use only. Audio generated by this script is fine for research
and training internal evaluation models; if your final LID router will ship
commercially, plan to regenerate the training set with a permissively-licensed
backend (or accept that the audio data lineage may limit downstream rights)
before launch.
"""

